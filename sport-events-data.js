window.ADC_SPORT_EVENTS.getEventsForSport = function (sport) {
  var c = this.catalog[sport];
  if (c) return c.events || [];
  var keys = Object.keys(this.catalog);
  for (var i = 0; i < keys.length; i++) {
    var item = this.catalog[keys[i]];
    if (item.sportRaw && String(item.sportRaw).toLowerCase() === String(sport || '').toLowerCase()) return item.events || [];
  }
  return [];
};
window.ADC_SPORT_EVENTS.listSports = function () { return Object.keys(this.catalog); };
